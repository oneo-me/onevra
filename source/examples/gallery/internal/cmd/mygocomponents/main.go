// Command mygocomponents inventories the pinned MyGo UI source without loading native code.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type component struct{ Name, Source string }

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	cmd := exec.Command("go", "list", "-m", "-json", "github.com/egoist/mygo")
	cmd.Stderr = os.Stderr
	data, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("locate MyGo: %w", err)
	}
	var module struct{ Dir, Version string }
	if err := json.Unmarshal(data, &module); err != nil {
		return err
	}
	if module.Dir == "" {
		return fmt.Errorf("MyGo module has no source directory")
	}
	entries, err := scan(filepath.Join(module.Dir, "ui"))
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		return fmt.Errorf("no MyGo UI constructors found")
	}
	var out bytes.Buffer
	fmt.Fprint(&out, "// Code generated by mygocomponents; DO NOT EDIT.\n\npackage gallery\n\n")
	fmt.Fprintf(&out, "const mygoScanVersion = %q\n\nvar mygoDiscovered = []mygoComponent{\n", module.Version)
	for _, entry := range entries {
		fmt.Fprintf(&out, "{Name: %q, Source: %q},\n", entry.Name, entry.Source)
	}
	fmt.Fprintln(&out, "}")
	generated, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	const output = "mygo_components_gen.go"
	previous, err := os.ReadFile(output)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if bytes.Equal(previous, generated) {
		return nil
	}
	return os.WriteFile(output, generated, 0644)
}

// Scan all platform files, not only the generator host's build selection.
// Exported free functions taking *Context first are UI entry points, including
// generic constructors and helpers such as AlertDialog that do not return Element.
// Base APIs remain implementation building blocks, not review candidates.
func scan(dir string) ([]component, error) {
	files, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	found := map[string]component{}
	for _, file := range files {
		name := file.Name()
		if file.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		parsed, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, err
		}
		if parsed.Name.Name != "ui" {
			continue
		}
		for _, decl := range parsed.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || !fn.Name.IsExported() || strings.Contains(fn.Name.Name, "Base") || len(fn.Type.Params.List) == 0 {
				continue
			}
			pointer, ok := fn.Type.Params.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			typ, ok := pointer.X.(*ast.Ident)
			if !ok || typ.Name != "Context" {
				continue
			}
			// Multiple platform implementations share one logical component.
			if _, exists := found[fn.Name.Name]; !exists {
				found[fn.Name.Name] = component{fn.Name.Name, "ui/" + name}
			}
		}
	}
	entries := make([]component, 0, len(found))
	for _, entry := range found {
		entries = append(entries, entry)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name < entries[j].Name })
	return entries, nil
}
